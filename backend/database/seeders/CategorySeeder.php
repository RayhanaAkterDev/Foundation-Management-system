            Category::updateOrCreate(
                ['slug' => $category['slug']],
                [
                    'name' => $category['name'],
                    'description' => $category['description'],
                    'about' => $category['about'],
                    'support_types' => $category['support_types'],
                    'image' => $category['image'],
                    'featured' => $category['featured'],
                    'active' => true,
                ]
            );
        }
    }
